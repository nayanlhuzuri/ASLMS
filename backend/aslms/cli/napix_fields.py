"""`aslms napix-fields` — the field inventory: every key path seen in the decrypted samples, per API, with its
type and an example. It is the input to the schema coverage addendum (plan step 3): a field in this inventory
without a table.column in docs/schema/schema.md is a defect."""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any

import typer
from rich import print as rprint

from aslms.integration.napix.client import nested_list

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SAMPLES = REPO_ROOT / "docs" / "specs" / "samples"
DEFAULT_OUT = REPO_ROOT / "docs" / "specs" / "napix_field_inventory.md"
NUMBERED = re.compile(r"^[A-Za-z_]+\d+$")


def _is_numbered_list(d: dict[str, Any]) -> bool:
    return bool(d) and all(NUMBERED.match(str(k)) and isinstance(v, dict) for k, v in d.items())


def walk(obj: Any, path: str, out: dict[str, dict[str, Any]]) -> None:
    """Flattens `{"case1": {...}}` into `[]`-paths so repeating blocks are one entry."""
    if isinstance(obj, dict):
        if _is_numbered_list(obj):
            for row in nested_list(obj):
                walk(row, f"{path}[]", out)
            return
        for k, v in obj.items():
            walk(v, f"{path}.{k}" if path else str(k), out)
        return
    if isinstance(obj, list):
        for v in obj:
            walk(v, f"{path}[]", out)
        return
    entry = out.setdefault(path, {"types": set(), "example": None, "seen": 0, "empty": 0})
    entry["seen"] += 1
    t = "null" if obj is None else type(obj).__name__
    entry["types"].add(t)
    if obj in (None, "", [], {}):
        entry["empty"] += 1
    elif entry["example"] is None:
        entry["example"] = str(obj)[:60]


def api_name(file: Path) -> str:
    return re.sub(r"(_bench\d+)?_\d{4}-\d{2}-\d{2}$|_response$", "", file.stem)


def build_inventory(samples: Path) -> dict[str, dict[str, dict[str, Any]]]:
    inv: dict[str, dict[str, dict[str, Any]]] = defaultdict(dict)
    for f in sorted(samples.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if isinstance(data, dict) and "response_str" in data:
            continue  # an encrypted envelope saved by hand; `napix-check` writes decrypted samples
        walk(data, "", inv[api_name(f)])
    return inv


def render(inv: dict[str, dict[str, dict[str, Any]]]) -> str:
    lines = [
        "# NAPIX field inventory",
        "",
        "Generated by `aslms napix-fields` from the decrypted samples in `docs/specs/samples/`. `[]` marks a",
        "repeating block (`case1`, `case2`, … or a JSON list). Every path here must have a table.column in",
        "`docs/schema/schema.md` (coverage table). Regenerate after each `napix-check`.",
        "",
    ]
    for api, fields in sorted(inv.items()):
        lines += [f"## {api}", "", "| path | type | example | seen | empty |", "|---|---|---|---|---|"]
        for path, e in sorted(fields.items()):
            ex = (e["example"] or "").replace("|", "\\|")
            lines.append(
                f"| `{path}` | {', '.join(sorted(e['types']))} | {ex} | {e['seen']} | {e['empty']} |"
            )
        lines.append("")
    return "\n".join(lines)


def napix_fields(
    samples: Path = typer.Option(DEFAULT_SAMPLES, help="decrypted samples written by napix-check"),
    out: Path = typer.Option(DEFAULT_OUT, help="inventory markdown to write"),
) -> None:
    """Build the NAPIX field inventory from the saved samples."""
    inv = build_inventory(samples)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(inv), encoding="utf-8", newline="\n")
    n = sum(len(v) for v in inv.values())
    rprint(f"[green]{n} field paths across {len(inv)} APIs[/green] → {out}")
