def _reopen_once_function() -> str:
    """The closer's columns never change; the reopening columns change once, from NULL. `actor_user_id` may still be
    set to NULL by its SET NULL foreign key (a login is never deleted, but the key allows it)."""
    fixed = " OR ".join(f"NEW.{c} IS DISTINCT FROM OLD.{c}" for c in FIXED_COLUMNS if c != "actor_user_id")
    fixed += " OR (NEW.actor_user_id IS NOT NULL AND NEW.actor_user_id IS DISTINCT FROM OLD.actor_user_id)"
    once = " OR ".join(
        f"(OLD.{c} IS NOT NULL AND NEW.{c} IS DISTINCT FROM OLD.{c})"
        for c in REOPEN_COLUMNS
        if c != "reopened_by_user_id"
    )
    return f"""
        CREATE OR REPLACE FUNCTION aslms_case_closure_reopen_once() RETURNS trigger AS $$
        BEGIN
            IF {fixed} THEN
                RAISE EXCEPTION 'case_closures: only the reopening columns may change'
                    USING ERRCODE = 'check_violation';
            END IF;
            IF OLD.reopened_at IS NOT NULL AND (
                {once}
                OR (NEW.reopened_by_user_id IS NOT NULL
                    AND NEW.reopened_by_user_id IS DISTINCT FROM OLD.reopened_by_user_id)
            ) THEN
                RAISE EXCEPTION 'case_closures: a closure is reopened once'
                    USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END
        $$ LANGUAGE plpgsql
    """


