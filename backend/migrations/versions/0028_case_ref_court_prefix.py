"""0028 case reference numbers carry the court's code: `courts.ref_code` and the one-time renumbering

Design `case-ref-court-prefix` ("Data", decisions 2 and 6-16); docs/DB_STANDARD.md v1.3 §3 and §3a;
docs/schema/schema.md, Conventions "Reference numbers" and "Extensions", Group 2 row `courts`, Group 3 row `cases`
and the `ref_sequences` row. The design names it "the next free number"; 0026 and 0027 are taken, so it is 0028.
Autogenerated against the dev database (it found only the column), then written by hand: autogenerate cannot write the
extension, the exclusion constraint or the data steps. Plain SQL with no application import beyond
`aslms.db.migration_audit`, so it stays frozen once applied. No grant changes: `aslms_app` already has SELECT on
`courts`, and UPDATE on `cases` and `ref_sequences` here is the owner's.

Upgrade, in one transaction (it refuses, changing nothing, when the rule cannot map everything):
1. Guards (decision 8): every case number matches `^ASLMS/GOA/CASE/[0-9]{4}/[0-9]{6}$`; every case's court is an
   establishment of the Gauhati High Court (`high_courts.napix_state_code = 18`); no office holds `GHC`; no `GHC`
   CASE counter exists.
2. `CREATE EXTENSION IF NOT EXISTS btree_gist`.
3. `courts.ref_code varchar(10)`: added nullable, `GHC` on every Gauhati High Court establishment, refused when a
   court is left without a code, then NOT NULL with CHECK `ck_courts_ref_code_format` and the exclusion
   `ex_courts_ref_code_one_court` (one code per court of record; establishments of one High Court share it).
4. With the trigger `cases_updated_at` disabled (decision 10): `ASLMS/GOA/CASE/` becomes `ASLMS/GHC/CASE/` with the
   same year and number on every case, provisional and merged ones included, and every search vector is recomputed
   with `aslms_case_search_vector(id)` (decision 11).
5. Each (`GOA`, `CASE`, year) counter becomes (`GHC`, `CASE`, year) with `last_value` = the greater of the counter
   and the highest number held for that year; the `GOA` CASE rows are deleted (decision 9).
6. CHECK `ck_cases_ref_no_court` (decision 12).
7. One summary audit row `case.ref_renumbered` through `audit_once` (decision 13), when there was anything to
   renumber (a case or a CASE counter); an empty database has nothing to record.

Downgrade (decision 14): refused when a case number has a court code other than `GHC`. Otherwise the CHECK is dropped,
every `ASLMS/GHC/CASE/` goes back to `ASLMS/GOA/CASE/` (trigger disabled, vectors recomputed), the counters move back,
the exclusion, the format CHECK, the column and `btree_gist` are dropped, and `record_downgrade` is called last.
Events, audit rows and job results keep the numbers of their time (append-only history, decision 21).

Revision ID: 0028
Revises: 0027
Create Date: 2026-10-26
"""

from __future__ import annotations

import sqlalchemy as sa
from alembic import op

from aslms.db.migration_audit import audit_once, record_downgrade

revision = "0028"
down_revision = "0027"
branch_labels = None
depends_on = None

MIGRATION = "0028"
OLD_CODE = "GOA"
NEW_CODE = "GHC"
OLD_PREFIX = "ASLMS/GOA/CASE/"
NEW_PREFIX = "ASLMS/GHC/CASE/"
GAUHATI_STATE_CODE = 18
OWNER_DECISION = "2026-10-25"
AUDIT_KEY = "case_ref_court_prefix"

CASE_CHECK = "ck_cases_ref_no_court"
COURT_CHECK = "ck_courts_ref_code_format"
COURT_EXCLUDE = "ex_courts_ref_code_one_court"


class RenumberRefused(RuntimeError):
    """The rule cannot map the data: nothing is changed."""


def _scalar(bind, sql: str, **params):
    return bind.execute(sa.text(sql), params).scalar()


def _refuse(message: str) -> None:
    raise RenumberRefused(f"migration {MIGRATION} (case-ref-court-prefix) refused: {message}")


def _guards(bind) -> None:
    pattern = "^ASLMS/GOA/CASE/[0-9]{4}/[0-9]{6}$"
    bad = _scalar(bind, "SELECT count(*) FROM cases WHERE ref_no !~ :p", p=pattern)
    if bad:
        example = _scalar(
            bind, "SELECT ref_no FROM cases WHERE ref_no !~ :p ORDER BY ref_no LIMIT 1", p=pattern
        )
        _refuse(f"{bad} case number(s) are not of the form ASLMS/GOA/CASE/<YYYY>/<NNNNNN> (e.g. {example})")
    other = _scalar(
        bind,
        "SELECT count(*) FROM cases ca JOIN courts c ON c.id = ca.court_id "
        "LEFT JOIN high_courts h ON h.id = c.high_court_id "
        "WHERE h.napix_state_code IS DISTINCT FROM :state",
        state=GAUHATI_STATE_CODE,
    )
    if other:
        _refuse(f"{other} case(s) belong to a court that is not a Gauhati High Court establishment")
    if _scalar(bind, "SELECT EXISTS (SELECT 1 FROM offices WHERE code = :code)", code=NEW_CODE):
        _refuse(f"an office holds the code {NEW_CODE}")
    if _scalar(
        bind,
        "SELECT EXISTS (SELECT 1 FROM ref_sequences WHERE office_code = :code AND record_type = 'CASE')",
        code=NEW_CODE,
    ):
        _refuse(f"a {NEW_CODE} CASE counter already exists")


def _rewrite_cases(bind, old_prefix: str, new_prefix: str) -> None:
    """Every case number from one prefix to the other, and every vector again, without bumping `updated_at`."""
    bind.execute(sa.text("ALTER TABLE cases DISABLE TRIGGER cases_updated_at"))
    bind.execute(
        sa.text("UPDATE cases SET ref_no = :new || substr(ref_no, :len + 1) WHERE left(ref_no, :len) = :old"),
        {"old": old_prefix, "new": new_prefix, "len": len(old_prefix)},
    )
    bind.execute(sa.text("UPDATE cases SET search_vector = aslms_case_search_vector(id)"))
    bind.execute(sa.text("ALTER TABLE cases ENABLE TRIGGER cases_updated_at"))


def _move_counters(bind, old_code: str, new_code: str, new_prefix: str) -> list[dict]:
    """The CASE counters of `old_code` become `new_code` rows, each at least the highest number held for its year
    (the cases already carry `new_prefix`); the old rows are deleted. Returns [{year, last_value}]."""
    rows = bind.execute(
        sa.text(
            """
            WITH held AS (
                SELECT substr(ref_no, :len + 1, 4)::smallint AS year,
                       max(substr(ref_no, :len + 6, 6)::integer) AS top
                FROM cases WHERE left(ref_no, :len) = :prefix GROUP BY 1
            ), counters AS (
                SELECT year, last_value FROM ref_sequences WHERE office_code = :old AND record_type = 'CASE'
            )
            INSERT INTO ref_sequences (office_code, record_type, year, last_value)
            SELECT :new, 'CASE', COALESCE(c.year, h.year), greatest(COALESCE(c.last_value, 0), COALESCE(h.top, 0))
            FROM counters c FULL JOIN held h ON h.year = c.year
            ON CONFLICT (office_code, record_type, year)
            DO UPDATE SET last_value = greatest(ref_sequences.last_value, EXCLUDED.last_value)
            RETURNING year, last_value
            """
        ),
        {"old": old_code, "new": new_code, "prefix": new_prefix, "len": len(new_prefix)},
    ).all()
    bind.execute(
        sa.text("DELETE FROM ref_sequences WHERE office_code = :old AND record_type = 'CASE'"),
        {"old": old_code},
    )
    return sorted(
        ({"year": int(r.year), "last_value": int(r.last_value)} for r in rows), key=lambda d: d["year"]
    )


def upgrade() -> None:
    bind = op.get_bind()
    _guards(bind)
    counts = bind.execute(
        sa.text(
            "SELECT count(*) AS cases, count(*) FILTER (WHERE is_provisional) AS provisional, "
            "count(*) FILTER (WHERE merged_into_case_id IS NOT NULL) AS merged FROM cases"
        )
    ).one()
    had_counters = bool(
        _scalar(
            bind,
            "SELECT EXISTS (SELECT 1 FROM ref_sequences WHERE office_code = :code AND record_type = 'CASE')",
            code=OLD_CODE,
        )
    )

    op.execute("CREATE EXTENSION IF NOT EXISTS btree_gist")
    op.add_column("courts", sa.Column("ref_code", sa.String(length=10), nullable=True))
    bind.execute(
        sa.text(
            "UPDATE courts SET ref_code = :code "
            "WHERE high_court_id = (SELECT id FROM high_courts WHERE napix_state_code = :state)"
        ),
        {"code": NEW_CODE, "state": GAUHATI_STATE_CODE},
    )
    missing = _scalar(
        bind, "SELECT string_agg(est_code, ', ' ORDER BY est_code) FROM courts WHERE ref_code IS NULL"
    )
    if missing:
        _refuse(
            f"no court code can be given to {missing} (only Gauhati High Court establishments get {NEW_CODE})"
        )
    op.alter_column("courts", "ref_code", nullable=False)
    op.create_check_constraint(
        op.f(COURT_CHECK), "courts", "ref_code ~ '^[A-Z][A-Z0-9]{1,9}$' AND ref_code <> 'GOA'"
    )
    op.execute(
        f"ALTER TABLE courts ADD CONSTRAINT {COURT_EXCLUDE} "
        "EXCLUDE USING gist (ref_code WITH =, (COALESCE(high_court_id, id)) WITH <>)"
    )

    _rewrite_cases(bind, OLD_PREFIX, NEW_PREFIX)
    sequences = _move_counters(bind, OLD_CODE, NEW_CODE, NEW_PREFIX)
    op.create_check_constraint(
        op.f(CASE_CHECK),
        "cases",
        "ref_no ~ '^ASLMS/[A-Z][A-Z0-9]{1,9}/CASE/[0-9]{4}/[0-9]{6}$' AND ref_no NOT LIKE 'ASLMS/GOA/%'",
    )

    if counts.cases or had_counters:
        first, last = bind.execute(sa.text("SELECT min(ref_no), max(ref_no) FROM cases")).one()
        audit_once(
            bind,
            "case.ref_renumbered",
            AUDIT_KEY,
            revision=MIGRATION,
            entity_type="system",
            after={
                "from_prefix": OLD_PREFIX,
                "to_prefix": NEW_PREFIX,
                "cases": int(counts.cases),
                "provisional": int(counts.provisional),
                "merged": int(counts.merged),
                "first": first,
                "last": last,
                "sequences": sequences,
                "rule": "same year and number",
                "owner_decision": OWNER_DECISION,
            },
        )


def downgrade() -> None:
    bind = op.get_bind()
    params = {"len": len(NEW_PREFIX), "prefix": NEW_PREFIX}
    other = _scalar(bind, "SELECT count(*) FROM cases WHERE left(ref_no, :len) <> :prefix", **params)
    if other:
        example = _scalar(
            bind,
            "SELECT ref_no FROM cases WHERE left(ref_no, :len) <> :prefix ORDER BY ref_no LIMIT 1",
            **params,
        )
        _refuse(
            f"downgrade: {other} case number(s) carry a court code other than {NEW_CODE} (e.g. {example}); "
            f"only {NEW_CODE} maps back to {OLD_CODE}"
        )
    op.drop_constraint(op.f(CASE_CHECK), "cases", type_="check")
    _rewrite_cases(bind, NEW_PREFIX, OLD_PREFIX)
    _move_counters(bind, NEW_CODE, OLD_CODE, OLD_PREFIX)
    op.execute(f"ALTER TABLE courts DROP CONSTRAINT {COURT_EXCLUDE}")
    op.drop_constraint(op.f(COURT_CHECK), "courts", type_="check")
    op.drop_column("courts", "ref_code")
    op.execute("DROP EXTENSION IF EXISTS btree_gist")
    record_downgrade(bind, MIGRATION, down_revision)
