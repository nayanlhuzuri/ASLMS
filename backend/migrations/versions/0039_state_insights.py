def _fixed_function() -> str:
    return """
        CREATE OR REPLACE FUNCTION aslms_insight_group_fixed() RETURNS trigger AS $$
        BEGIN
            IF NEW.kind IS DISTINCT FROM OLD.kind OR NEW.code IS DISTINCT FROM OLD.code
               OR NEW.is_reserved IS DISTINCT FROM OLD.is_reserved THEN
                RAISE EXCEPTION 'insight_groups: kind, code and is_reserved never change'
                    USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END
        $$ LANGUAGE plpgsql
    """


def _reference_rows(bind) -> None:
    reserved = set(RESERVED)
    for kind, groups in (("family", FAMILY_GROUPS), ("subject", SUBJECT_GROUPS)):
        for order, (code, label) in enumerate(groups, start=1):
            bind.execute(
                sa.text(
                    "INSERT INTO insight_groups (kind, code, label, sort_order, is_reserved) "
                    "VALUES (:kind, :code, :label, :sort_order, :reserved) ON CONFLICT (kind, code) DO NOTHING"
                ),
                {
                    "kind": kind,
                    "code": code,
                    "label": label,
                    "sort_order": order * 10,
                    "reserved": (kind, code) in reserved,
                },
            )
    for code, label, group in CATEGORIES:
        bind.execute(
            sa.text(
                "INSERT INTO insight_subject_categories (court_id, category_code, label, group_id, group_kind) "
                "SELECT c.id, :code, :label, g.id, 'subject' FROM courts c "
                "JOIN insight_groups g ON g.kind = 'subject' AND g.code = :grp "
                "WHERE c.ref_code = :court ON CONFLICT (court_id, category_code) DO NOTHING"
            ),
            {"code": code, "label": label, "grp": group, "court": COURT_REF_CODE},
        )
    for type_code, group in CASE_TYPES:
        bind.execute(
            sa.text(
                "INSERT INTO insight_case_type_groups (case_type_id, group_id, group_kind) "
                "SELECT ct.id, g.id, 'family' FROM case_types ct JOIN courts c ON c.id = ct.court_id "
                "JOIN insight_groups g ON g.kind = 'family' AND g.code = :grp "
                "WHERE c.ref_code = :court AND ct.case_type_code = :type_code "
                "ON CONFLICT (case_type_id) DO NOTHING"
            ),
            {"type_code": type_code, "grp": group, "court": COURT_REF_CODE},
        )


